'use strict';
// VENDOR THE CREATIVE WEB FONTS (lib/creative/fonts.js): for every open-source face in the registry, the npm package
// @fontsource/<id> (SIL Open Font License 1.1 -- checked from each package's own package.json) is packed, and only what a
// page can use is kept: the Latin .woff2 at the weights the registry sets text in (headline, body 400/700, label), and the
// licence. Each face is measured from its own .woff twin (scripts/font-metrics.js): how wide it sets a headline.
// Writes vendor/creative-fonts/<id>-<weight>.woff2, vendor/creative-fonts/<id>.LICENSE.txt and lib/creative/fonts-data.json.
// Run by hand when the registry changes:  node scripts/vendor-creative-fonts.js   (network: the npm registry only)
const fs = require('fs');
const os = require('os');
const path = require('path');
const zlib = require('zlib');
const crypto = require('crypto');
const { execFileSync } = require('child_process');
const M = require('./font-metrics');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'vendor', 'creative-fonts');
const DATA = path.join(ROOT, 'lib', 'creative', 'fonts-data.json');
const VERSION = '5.3.0';
if (!fs.existsSync(DATA)) fs.writeFileSync(DATA, JSON.stringify({ fonts: {} }));
const { LIST } = require('../lib/creative/fonts');

// a .tgz's files, by name (ustar: 512-byte headers, the name at 0, the size in octal at 124, a prefix at 345)
function untar(tgz) {
  const buf = zlib.gunzipSync(tgz); const files = new Map(); let o = 0;
  while (o + 512 <= buf.length) {
    const name = buf.toString('utf8', o, o + 100).replace(/\0.*$/s, ''); if (!name) break;
    const prefix = buf.toString('utf8', o + 345, o + 500).replace(/\0.*$/s, '');
    const size = parseInt(buf.toString('ascii', o + 124, o + 136).replace(/\0.*$/s, '').trim() || '0', 8);
    files.set(prefix ? `${prefix}/${name}` : name, buf.subarray(o + 512, o + 512 + size));
    o += 512 + Math.ceil(size / 512) * 512;
  }
  return files;
}
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sr-fonts-'));
fs.mkdirSync(OUT, { recursive: true });
const data = { note: 'Generated by scripts/vendor-creative-fonts.js -- do not edit by hand.', source: 'Fontsource (npm @fontsource/<id>)', fonts: {} };
for (const f of LIST.filter(x => x.source === 'web')) {
  const name = execFileSync(npm, ['pack', `@fontsource/${f.id}@${VERSION}`, '--silent', '--pack-destination', tmp], { encoding: 'utf8', shell: process.platform === 'win32' }).trim().split('\n').pop();
  const files = untar(fs.readFileSync(path.join(tmp, name)));
  const pkg = JSON.parse(files.get('package/package.json').toString('utf8'));
  if (pkg.license !== 'OFL-1.1' && pkg.license !== 'Apache-2.0') throw new Error(`${f.id}: licence ${pkg.license} is not one SiteRemade may redistribute`);
  const meta = JSON.parse(files.get('package/metadata.json').toString('utf8'));
  if (!(meta.subsets || []).includes('latin')) throw new Error(`${f.id}: no Latin subset`);
  const have = (meta.weights || []).map(Number);
  const pick = w => have.reduce((b, x) => (Math.abs(x - w) < Math.abs(b - w) ? x : b), have[0]);
  const want = [...new Set([f.hw, 400, 700, f.lw].map(pick))].sort((a, b) => a - b);
  const entry = { pkg: `@fontsource/${f.id}`, version: pkg.version, license: pkg.license, licenseFile: `${f.id}.LICENSE.txt`, weights: {} };
  for (const w of want) {
    const woff2 = files.get(`package/files/${f.id}-latin-${w}-normal.woff2`); const woff = files.get(`package/files/${f.id}-latin-${w}-normal.woff`);
    if (!woff2 || !woff) throw new Error(`${f.id}: no Latin ${w} file`);
    const file = `${f.id}-${w}.woff2`; fs.writeFileSync(path.join(OUT, file), woff2);
    const m = M.measure(woff);
    entry.weights[String(w)] = { file, bytes: woff2.length, sha256: crypto.createHash('sha256').update(woff2).digest('hex'), adv: +m.adv.toFixed(4), upper: +m.upper.toFixed(4) };
  }
  const lic = files.get('package/LICENSE'); if (!lic) throw new Error(`${f.id}: no licence file`);
  fs.writeFileSync(path.join(OUT, entry.licenseFile), lic);
  data.fonts[f.id] = entry;
  console.log(f.id.padEnd(22), pkg.license, want.join('/'), Object.values(entry.weights).map(x => x.bytes).reduce((a, b) => a + b, 0), 'bytes');
}
fs.writeFileSync(DATA, JSON.stringify(data, null, 1) + '\n');
fs.rmSync(tmp, { recursive: true, force: true });
const total = Object.values(data.fonts).reduce((t, d) => t + Object.values(d.weights).reduce((a, x) => a + x.bytes, 0), 0);
console.log(`${Object.keys(data.fonts).length} faces, ${Object.values(data.fonts).reduce((t, d) => t + Object.keys(d.weights).length, 0)} files, ${(total / 1024).toFixed(0)} KB`);

'use strict';
// Bundles lib/premium/*.js into ONE browser-loadable file, premium-core.js at
// the repo root (exposes window.SiteRemadePremium; also a valid CommonJS
// module). script.js is a browser global-scope script and cannot require(),
// so this is how the browser runs the exact same code the server runs.
//
//   node scripts/build-premium-core.js          write premium-core.js
//   node scripts/build-premium-core.js --check  exit 1 if premium-core.js is stale
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'lib', 'premium');
const OUT = path.join(ROOT, 'premium-core.js');

function build() {
  const files = fs.readdirSync(DIR).filter(f => f.endsWith('.js')).sort();
  const parts = files.map(f => {
    const name = f.replace(/\.js$/, '');
    const src = fs.readFileSync(path.join(DIR, f), 'utf8').replace(/\r\n/g, '\n');
    return `  __define(${JSON.stringify(name)}, function (module, exports, require) {\n${src.split('\n').map(l => (l ? '    ' + l : l)).join('\n')}\n  });`;
  });
  return `/* GENERATED by scripts/build-premium-core.js from lib/premium/*.js -- do not edit by hand.
   PREMIUM_GENERATION_V1 shared core, bundled for the browser. */
(function (root) {
  'use strict';
  var __mods = {}, __cache = {};
  function __define(name, fn) { __mods[name] = fn; }
  function __require(name) {
    name = String(name).replace(/^\\.\\//, '');
    if (__cache[name]) return __cache[name].exports;
    if (!__mods[name]) throw new Error('premium-core: unknown module ' + name);
    var m = { exports: {} }; __cache[name] = m;
    __mods[name](m, m.exports, __require);
    return m.exports;
  }
${parts.join('\n')}
  var api = __require('index');
  api.mobile = __require('mobile-check');
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.SiteRemadePremium = api;
})(typeof window !== 'undefined' ? window : (typeof globalThis !== 'undefined' ? globalThis : this));
`;
}

const built = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== built) { console.error('premium-core.js is stale: run node scripts/build-premium-core.js'); process.exit(1); }
  console.log('premium-core.js is up to date');
} else {
  fs.writeFileSync(OUT, built);
  console.log('wrote premium-core.js (' + built.length + ' bytes)');
}

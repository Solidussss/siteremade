'use strict';
// Bundles the browser-safe Creative modules (lib/creative: understand, assets, director,
// validate, render) into ONE file, creative-core.js at the repo root (window.SiteRemadeCreative;
// also a CommonJS module). Loaded by creative.js ONLY when someone opens Creative mode --
// the Business builder never downloads it. Same pattern as scripts/build-premium-core.js.
//
//   node scripts/build-creative-core.js          write creative-core.js
//   node scripts/build-creative-core.js --check  exit 1 if creative-core.js is stale
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'lib', 'creative');
const OUT = path.join(ROOT, 'creative-core.js');
const MODULES = ['understand', 'assets', 'validate', 'validate2', 'director', 'render', 'render2']; // server-only: ai, png, research, store

function build() {
  const parts = MODULES.map(name => {
    const src = fs.readFileSync(path.join(DIR, `${name}.js`), 'utf8').replace(/\r\n/g, '\n');
    return `  __define(${JSON.stringify(name)}, function (module, exports, require) {\n${src.split('\n').map(l => (l ? '    ' + l : l)).join('\n')}\n  });`;
  });
  return `/* GENERATED by scripts/build-creative-core.js from lib/creative/*.js -- do not edit by hand.
   Creative mode core, bundled for the browser. */
(function (root) {
  'use strict';
  var __mods = {}, __cache = {};
  function __define(name, fn) { __mods[name] = fn; }
  function __require(name) {
    name = String(name).replace(/^\\.\\//, '');
    if (__cache[name]) return __cache[name].exports;
    if (!__mods[name]) throw new Error('creative-core: unknown module ' + name);
    var m = { exports: {} }; __cache[name] = m;
    __mods[name](m, m.exports, __require);
    return m.exports;
  }
${parts.join('\n')}
  var api = { understand: __require('understand'), assets: __require('assets'), validate: __require('validate'), validate2: __require('validate2'), director: __require('director'), render: __require('render'), render2: __require('render2') };
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.SiteRemadeCreative = api;
})(typeof window !== 'undefined' ? window : (typeof globalThis !== 'undefined' ? globalThis : this));
`;
}

const built = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== built) { console.error('creative-core.js is stale: run node scripts/build-creative-core.js'); process.exit(1); }
  console.log('creative-core.js is up to date');
} else {
  fs.writeFileSync(OUT, built);
  console.log('wrote creative-core.js (' + built.length + ' bytes)');
}
